-- Container: DEV
-- User: APPS 
SELECT
  property_value AS default_edition
FROM
  database_properties
WHERE
  property_name = 'DEFAULT_EDITION';

-- all members of the specified roles
select
  grantee,
  granted_role,
  default_role,
  admin_option,
  delegate_option
from
  dba_role_privs
where
  granted_role in ('DNVGL_DEVELOPER_ROLE', 'DEVELOPER_ROLE')
order by
  granted_role,
  grantee;

-- privileges granted directly
select
  grantee,
  privilege
from
  dba_sys_privs
where
  grantee like 'DEV_%'
order by
  grantee,
  privilege;

-- privileges granted through roles
select
  rp.grantee,
  rp.granted_role,
  sp.privilege
from
  dba_role_privs rp
  join role_sys_privs sp on sp.role = rp.granted_role
where
  rp.grantee like 'DEV_%'
  and sp.privilege in (
    'CREATE ANY PROCEDURE',
    'ALTER ANY PROCEDURE',
    'CREATE ANY TABLE',
    'ALTER ANY TABLE',
    'CREATE ANY VIEW'
  )
order by
  rp.grantee,
  rp.granted_role,
  sp.privilege;

-- enabled audit policies
select
  policy_name,
  enabled_option,
  entity_name,
  entity_type,
  success,
  failure
from
  audit_unified_enabled_policies
order by
  policy_name;

-- all audit policies
select
  policy_name,
  audit_option,
  object_schema,
  object_name,
  condition_eval_opt
from
  audit_unified_policies
order by
  policy_name,
  object_schema,
  object_name;
